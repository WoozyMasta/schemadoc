func TestCLI_Schema2Doc(t *testing.T) {
	t.Parallel()

	schemaPath := repoTestdataPath(t, "generated", "app.schema.json")
	customTemplatePath := filepath.Join(t.TempDir(), "custom.gotmpl")
	if err := os.WriteFile(
		customTemplatePath,
		[]byte("# custom\n{{ range .Definitions }}- {{ .Name }}\n{{ end }}\n"),
		0o600,
	); err != nil {
		t.Fatalf("write custom template: %v", err)
	}

	testCases := []struct {
		name        string
		args        []string
		stdin       io.Reader
		outFile     string
		code        int
		stdoutHas   []string
		stdoutNoHas []string
		stderrHas   []string
		fileHas     []string
		fileNoHas   []string
	}{
		{
			name:      "default to stdout",
			args:      []string{"schema2doc", schemaPath},
			code:      0,
			stdoutHas: []string{"# schema reference"},
		},
		{
			name:      "table template",
			args:      []string{"schema2doc", "--template", "table", schemaPath},
			code:      0,
			stdoutHas: []string{"| Attribute | Value |"},
		},
		{
			name:      "html template",
			args:      []string{"schema2doc", "--template", "html", schemaPath},
			code:      0,
			stdoutHas: []string{"<!DOCTYPE html>"},
		},
		{
			name: "stdin schema",
			args: []string{"schema2doc"},
			stdin: strings.NewReader(`{
  "$schema": "https://json-schema.org/draft/2020-12/schema",
  "$id": "urn:test",
  "type": "object",
  "properties": { "name": { "type": "string" } }
}`),
			code:        0,
			stdoutHas:   []string{"## Root"},
			stdoutNoHas: []string{"Source schema:"},
		},
		{
			name:    "write output file",
			args:    []string{"schema2doc", "--title", "Custom Doc", schemaPath},
			outFile: filepath.Join(t.TempDir(), "schema.md"),
			code:    0,
			fileHas: []string{"# Custom Doc"},
		},
		{
			name:      "custom description",
			args:      []string{"schema2doc", "--description", "Generated by CI.", schemaPath},
			code:      0,
			stdoutHas: []string{"Generated by CI."},
		},
		{
			name:      "custom template file",
			args:      []string{"schema2doc", "--template-file", customTemplatePath, schemaPath},
			code:      0,
			stdoutHas: []string{"# custom"},
		},
		{
			name: "wrap width and list marker normalization",
			args: []string{"schema2doc", "--wrap", "24", "--list-marker", "*"},
			stdin: strings.NewReader(`{
  "$schema":"https://json-schema.org/draft/2020-12/schema",
  "type":"object",
  "properties":{"template_name":{"type":"string","description":"Supported values:\n\n - list\n - table"}}
}`),
			code:        0,
			stdoutHas:   []string{"* list"},
			stdoutNoHas: []string{"\n - list"},
		},
		{
			name:      "embedded required yaml example",
			args:      []string{"schema2doc", "--mode", "required", "--format", "yaml", schemaPath},
			code:      0,
			stdoutHas: []string{"## Example yaml document", "```yaml", "name: demo-service", "retry:"},
			stdoutNoHas: []string{
				"mode:",
			},
		},
	}

	for index := range testCases {
		testCase := testCases[index]
		t.Run(testCase.name, func(t *testing.T) {
			var stdout bytes.Buffer
			var stderr bytes.Buffer
			args := append([]string{}, testCase.args...)
			if testCase.outFile != "" {
				args = append(args, testCase.outFile)
			}

			code := runWithIO(args, firstReader(testCase.stdin), &stdout, &stderr)
			if code != testCase.code {
				t.Fatalf("run exit code = %d, want %d; stderr: %s", code, testCase.code, stderr.String())
			}

			checkContainsAll(t, stderr.String(), testCase.stderrHas)
			checkContainsAll(t, stdout.String(), testCase.stdoutHas)
			checkNotContainsAny(t, stdout.String(), testCase.stdoutNoHas)

			if testCase.outFile != "" {
				data, err := os.ReadFile(testCase.outFile)
				if err != nil {
					t.Fatalf("read output file: %v", err)
				}

				content := string(data)
				checkContainsAll(t, content, testCase.fileHas)
				checkNotContainsAny(t, content, testCase.fileNoHas)
				if stdout.Len() != 0 {
					t.Fatalf("stdout should be empty for file output, got: %s", stdout.String())
				}
			}
		})
	}
}

func TestCLI_Schema2ExamplesAndTemplateAndConfig(t *testing.T) {
	t.Parallel()

	schemaPath := repoTestdataPath(t, "generated", "app.schema.json")
	jsonOut := filepath.Join(t.TempDir(), "required.json")
	yamlOut := filepath.Join(t.TempDir(), "required.yaml")

	testCases := []struct {
		name      string
		args      []string
		code      int
		stdoutHas []string
		stderrHas []string
	}{
		{
			name:      "template stdout",
			args:      []string{"template"},
			code:      0,
			stdoutHas: []string{"# {{ .Title }}"},
		},
		{
			name:      "config stdout",
			args:      []string{"config", "--mode", "all"},
			code:      0,
			stdoutHas: []string{"schema:"},
		},
		{
			name:      "schema2json stdout",
			args:      []string{"schema2json", schemaPath},
			code:      0,
			stdoutHas: []string{`"name": "demo-service"`, `"mode": "safe"`},
		},
		{
			name: "schema2json required file",
			args: []string{"schema2json", "--mode", "required", schemaPath, jsonOut},
			code: 0,
		},
		{
			name: "schema2yaml required file",
			args: []string{"schema2yaml", "--mode", "required", schemaPath, yamlOut},
			code: 0,
		},
	}

	for index := range testCases {
		testCase := testCases[index]
		t.Run(testCase.name, func(t *testing.T) {
			var stdout bytes.Buffer
			var stderr bytes.Buffer
			code := run(testCase.args, &stdout, &stderr)
			if code != testCase.code {
				t.Fatalf("run exit code = %d, want %d; stderr: %s", code, testCase.code, stderr.String())
			}

			checkContainsAll(t, stdout.String(), testCase.stdoutHas)
			checkContainsAll(t, stderr.String(), testCase.stderrHas)
		})
	}

	requiredJSON, err := os.ReadFile(jsonOut)
	if err != nil {
		t.Fatalf("read required json: %v", err)
	}

	checkContainsAll(t, string(requiredJSON), []string{
		`"name": "demo-service"`,
		`"retry": {`,
		`"shared": {`,
	})
	checkNotContainsAny(t, string(requiredJSON), []string{`"mode": "safe"`})

	requiredYAML, err := os.ReadFile(yamlOut)
	if err != nil {
		t.Fatalf("read required yaml: %v", err)
	}

	checkContainsAll(t, string(requiredYAML), []string{
		"# Service Name",
		"# Human-readable service name.",
		"name: demo-service",
		"# TLS Enabled",
		"# Enable TLS for outbound connections.",
		"enabled: true",
	})
}

func TestCLI_ConfigExampleOrderAndComments(t *testing.T) {
	t.Parallel()

	var stdout bytes.Buffer
	var stderr bytes.Buffer

	code := run([]string{"config"}, &stdout, &stderr)
	if code != 0 {
		t.Fatalf("run exit code = %d, want 0; stderr: %s", code, stderr.String())
	}

	output := stdout.String()
	checkContainsAll(t, output, []string{
		"# Schema is working schema path for the whole document pipeline.",
		"schema: schema.json",
		"check: false",
		"mod2schema:",
		"merge:",
		"schema2json:",
		"schema2doc:",
		"schema2yaml:",
		"output: <string>",
	})

	order := []string{
		"schema: schema.json",
		"check: false",
		"mod2schema:",
		"merge:",
		"schema2json:",
		"schema2doc:",
		"schema2yaml:",
	}

	last := -1
	for _, marker := range order {
		index := strings.Index(output, marker)
		if index < 0 {
			t.Fatalf("marker %q not found in output", marker)
		}

		if index <= last {
			t.Fatalf("marker %q is out of order", marker)
		}

		last = index
	}
}

