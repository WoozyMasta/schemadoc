func TestCLI_ModCommands(t *testing.T) {
	t.Parallel()

	moduleRoot := findModuleRoot(t)
	schemaOut := filepath.Join(t.TempDir(), "mod.schema.json")
	schemaYAMLOut := filepath.Join(t.TempDir(), "mod.schema.yaml")
	mdOut := filepath.Join(t.TempDir(), "mod.md")

	testCases := []struct {
		name      string
		args      []string
		code      int
		stdoutHas []string
		stderrHas []string
	}{
		{
			name:      "mod2schema stdout",
			args:      []string{"mod2schema", "--type", "SchemaModel", moduleRoot},
			code:      0,
			stdoutHas: []string{`"SchemaModel"`},
		},
		{
			name: "mod2schema file",
			args: []string{"mod2schema", "--type", "SchemaModel", moduleRoot, schemaOut},
			code: 0,
		},
		{
			name: "mod2schema yaml file",
			args: []string{"mod2schema", "--type", "SchemaModel", moduleRoot, schemaYAMLOut},
			code: 0,
		},
		{
			name: "mod2doc stdout",
			args: []string{"mod2doc", "--type", "SchemaModel", moduleRoot},
			code: 0, stdoutHas: []string{"# schema reference", "## Options"},
		},
		{
			name: "mod2doc file",
			args: []string{"mod2doc", "--type", "SchemaModel", "--title", "Schema Model", moduleRoot, mdOut},
			code: 0,
		},
		{
			name:      "invalid type",
			args:      []string{"mod2schema", "--type", "Schema-Model", moduleRoot},
			code:      1,
			stderrHas: []string{"run module schema generator:"},
		},
	}

	for index := range testCases {
		testCase := testCases[index]
		t.Run(testCase.name, func(t *testing.T) {
			var stdout bytes.Buffer
			var stderr bytes.Buffer
			code := run(testCase.args, &stdout, &stderr)
			if code != testCase.code {
				t.Fatalf("run exit code = %d, want %d; stderr: %s", code, testCase.code, stderr.String())
			}

			checkContainsAll(t, stdout.String(), testCase.stdoutHas)
			checkContainsAll(t, stderr.String(), testCase.stderrHas)
		})
	}

	schemaContent, err := os.ReadFile(schemaOut)
	if err != nil {
		t.Fatalf("read mod schema: %v", err)
	}
	checkContainsAll(t, string(schemaContent), []string{`"Options"`})

	schemaYAMLContent, err := os.ReadFile(schemaYAMLOut)
	if err != nil {
		t.Fatalf("read mod yaml schema: %v", err)
	}
	checkContainsAll(t, string(schemaYAMLContent), []string{"$defs:", "Options:"})
	checkNotContainsAny(t, string(schemaYAMLContent), []string{`"$defs"`})

	mdContent, err := os.ReadFile(mdOut)
	if err != nil {
		t.Fatalf("read mod markdown: %v", err)
	}
	checkContainsAll(t, string(mdContent), []string{"# Schema Model"})
}

func TestCLI_BuildAndMergeAndErrors(t *testing.T) {
	t.Parallel()

	schemaPath := repoTestdataPath(t, "generated", "app.schema.json")
	tempDir := t.TempDir()
	firstOut := filepath.Join(tempDir, "first.json")
	secondOut := filepath.Join(tempDir, "second.json")
	buildConfig := filepath.Join(tempDir, "build.yaml")
	buildConfigBody := strings.Join([]string{
		"schema: " + filepath.ToSlash(schemaPath),
		"schema2json:",
		"  output: " + filepath.ToSlash(firstOut),
		"---",
		"schema: " + filepath.ToSlash(schemaPath),
		"schema2json:",
		"  output: " + filepath.ToSlash(secondOut),
		"  mode: required",
		"",
	}, "\n")
	if err := os.WriteFile(buildConfig, []byte(buildConfigBody), 0o600); err != nil {
		t.Fatalf("write build config: %v", err)
	}

	invalidConfig := filepath.Join(tempDir, "invalid.yaml")
	if err := os.WriteFile(invalidConfig, []byte("schema2json:\n  output: out.json\n"), 0o600); err != nil {
		t.Fatalf("write invalid config: %v", err)
	}

	basePath := filepath.Join(tempDir, "base.schema.json")
	addonPath := filepath.Join(tempDir, "addon.schema.json")
	mergeOut := filepath.Join(tempDir, "merged.schema.json")
	if err := os.WriteFile(
		basePath,
		[]byte(`{"$schema":"https://json-schema.org/draft/2020-12/schema","$defs":{"Base":{"type":"object"}}}`),
		0o600,
	); err != nil {
		t.Fatalf("write base schema: %v", err)
	}
	if err := os.WriteFile(
		addonPath,
		[]byte(`{"$schema":"https://json-schema.org/draft/2020-12/schema","$defs":{"Linting_RunPolicyConfig":{"type":"object"}}}`),
		0o600,
	); err != nil {
		t.Fatalf("write addon schema: %v", err)
	}

	testCases := []struct {
		name      string
		args      []string
		code      int
		stderrHas []string
	}{
		{
			name: "build index 0 all docs",
			args: []string{"build", buildConfig},
			code: 0,
		},
		{
			name: "build index 1",
			args: []string{"build", buildConfig, "--index", "1"},
			code: 0,
		},
		{
			name:      "build index out of range",
			args:      []string{"build", buildConfig, "--index", "4"},
			code:      1,
			stderrHas: []string{"out of range"},
		},
		{
			name:      "build validation error",
			args:      []string{"build", invalidConfig},
			code:      1,
			stderrHas: []string{"validate config"},
		},
		{
			name: "merge defs",
			args: []string{"merge", basePath, mergeOut, "--merge-defs=/$defs=" + addonPath + "#/$defs"},
			code: 0,
		},
		{
			name: "missing command",
			args: []string{},
			code: 2,
		},
		{
			name:      "unknown template choice",
			args:      []string{"template", "--template", "missing"},
			code:      2,
			stderrHas: []string{"Invalid value"},
		},
		{
			name:      "missing schema file",
			args:      []string{"schema2doc", filepath.Join(tempDir, "missing.json")},
			code:      1,
			stderrHas: []string{"read schema input:"},
		},
		{
			name:      "unknown draft warning",
			args:      []string{"schema2doc", writeSchemaFixture(t, "https://json-schema.org/draft/2099-01/schema")},
			code:      0,
			stderrHas: []string{"warning: unsupported $schema value"},
		},
	}

	for index := range testCases {
		testCase := testCases[index]
		t.Run(testCase.name, func(t *testing.T) {
			var stdout bytes.Buffer
			var stderr bytes.Buffer
			code := run(testCase.args, &stdout, &stderr)
			if code != testCase.code {
				t.Fatalf("run exit code = %d, want %d; stderr: %s", code, testCase.code, stderr.String())
			}

			checkContainsAll(t, stderr.String(), testCase.stderrHas)
		})
	}

	if _, err := os.Stat(firstOut); err != nil {
		t.Fatalf("first build output missing: %v", err)
	}
	if _, err := os.Stat(secondOut); err != nil {
		t.Fatalf("second build output missing: %v", err)
	}

	mergeContent, err := os.ReadFile(mergeOut)
	if err != nil {
		t.Fatalf("read merged schema: %v", err)
	}
	checkContainsAll(t, string(mergeContent), []string{`"Linting_RunPolicyConfig"`})
}

