func TestCLI_BuildDerivesOutputPaths(t *testing.T) {
	t.Parallel()

	tempDir := t.TempDir()
	schemaPath := filepath.Join(tempDir, "config.schema.json")
	schemaFixture, err := os.ReadFile(repoTestdataPath(t, "generated", "app.schema.json"))
	if err != nil {
		t.Fatalf("read schema fixture: %v", err)
	}

	if err := os.WriteFile(schemaPath, schemaFixture, 0o600); err != nil {
		t.Fatalf("write schema fixture copy: %v", err)
	}

	configPath := filepath.Join(tempDir, "build-derived.yaml")
	configBody := strings.Join([]string{
		"schema: " + filepath.ToSlash(schemaPath),
		"schema2json: {}",
		"schema2yaml: {}",
		"schema2doc: {}",
		"---",
		"schema: " + filepath.ToSlash(schemaPath),
		"schema2doc:",
		"  template: table",
		"---",
		"schema: " + filepath.ToSlash(schemaPath),
		"schema2doc:",
		"  template: html",
		"",
	}, "\n")
	if err := os.WriteFile(configPath, []byte(configBody), 0o600); err != nil {
		t.Fatalf("write build config: %v", err)
	}

	var stdout bytes.Buffer
	var stderr bytes.Buffer
	code := run([]string{"build", configPath}, &stdout, &stderr)
	if code != 0 {
		t.Fatalf("run exit code = %d, want 0; stderr: %s", code, stderr.String())
	}

	base := strings.TrimSuffix(schemaPath, filepath.Ext(schemaPath))
	expectedOutputs := []string{
		base + ".json",
		base + ".yaml",
		base + ".list.md",
		base + ".table.md",
		base + ".html",
	}
	for _, path := range expectedOutputs {
		if _, err := os.Stat(path); err != nil {
			t.Fatalf("expected derived output %q: %v", path, err)
		}
	}
}

func firstReader(reader io.Reader) io.Reader {
	if reader != nil {
		return reader
	}

	return os.Stdin
}

func findModuleRoot(t *testing.T) string {
	t.Helper()

	dir, err := os.Getwd()
	if err != nil {
		t.Fatalf("get working dir: %v", err)
	}

	for {
		candidate := filepath.Join(dir, "go.mod")
		if _, err := os.Stat(candidate); err == nil {
			return dir
		}

		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}

		dir = parent
	}

	t.Fatal("module root with go.mod was not found")
	return ""
}

func writeSchemaFixture(t *testing.T, schemaURI string) string {
	t.Helper()

	dir := t.TempDir()
	path := filepath.Join(dir, "schema.json")
	body := `{
  "$schema": "` + schemaURI + `",
  "$id": "urn:test",
  "$ref": "#/$defs/Config",
  "$defs": {
    "Config": {
      "type": "object",
      "properties": {
        "name": {
          "type": "string"
        }
      }
    }
  }
}`
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatalf("write schema fixture: %v", err)
	}

	return path
}

func repoTestdataPath(t *testing.T, parts ...string) string {
	t.Helper()

	all := append([]string{findModuleRoot(t), "testdata"}, parts...)
	return filepath.Join(all...)
}

func checkContainsAll(t *testing.T, value string, expects []string) {
	t.Helper()

	for index := range expects {
		if !strings.Contains(value, expects[index]) {
			t.Fatalf("missing substring %q in:\n%s", expects[index], value)
		}
	}
}

func checkNotContainsAny(t *testing.T, value string, unexpected []string) {
	t.Helper()

	for index := range unexpected {
		if strings.Contains(value, unexpected[index]) {
			t.Fatalf("unexpected substring %q in:\n%s", unexpected[index], value)
		}
	}
}
